from dataclasses import dataclass, field
from typing import List, Tuple, Optional
from app.modules.findings import FindingSeverity


@dataclass
class CapturedResponse:
    """Captured HTTP response including transcript, status, headers, and body."""
    url: str
    method: str
    status: int
    headers: List[Tuple[str, str]] = field(default_factory=list)
    body: str = ""
    elapsed_ms: float = 0.0
    raw_text: str = ""
    truncated: bool = False

    def get_header(self, name: str) -> Optional[str]:
        """Case-insensitive lookup of first header value."""
        target = name.lower().strip()
        for k, v in self.headers:
            if k.lower().strip() == target:
                return v.strip()
        return None

    def get_headers(self, name: str) -> List[str]:
        """Case-insensitive lookup of all header values matching name (e.g. Set-Cookie)."""
        target = name.lower().strip()
        return [v.strip() for k, v in self.headers if k.lower().strip() == target]

    def has_header(self, name: str) -> bool:
        """Check if header exists."""
        return self.get_header(name) is not None


@dataclass
class CandidateFinding:
    """Normalized candidate vulnerability finding generated by pure check functions."""
    title: str
    category: str
    description: str
    severity: FindingSeverity
    affected_url: str
    cvss_score: Optional[float] = None
    cvss_vector: Optional[str] = None
    wstg_id: Optional[str] = None
    owasp_top10: Optional[str] = None
    cwe: Optional[str] = None
    remediation: Optional[str] = None
    evidence_label: Optional[str] = None
    evidence_content: Optional[str] = None
